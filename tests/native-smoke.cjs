const { chromium } = require('playwright');
const { spawn } = require('node:child_process');
const fs = require('node:fs/promises');
const path = require('node:path');
const net = require('node:net');
const assert = require('node:assert/strict');
const root = path.resolve('test-results/native');
const checks = [];
async function port() { return new Promise(resolve => { const s=net.createServer();s.listen(0,'127.0.0.1',()=>{const p=s.address().port;s.close(()=>resolve(p));});}); }
async function main() {
  await fs.mkdir(root,{recursive:true});
  const fixture=path.join(root,'fixture.md');
  await fs.copyFile('samples/teams.md',fixture);
  await fs.copyFile('public/icon.png',path.join(root,'local.png'));
  const debugPort=await port();
  const exe=process.env.FOLIO_TEST_EXECUTABLE || path.resolve('src-tauri/target/debug/folio.exe');
  const proc=spawn(exe,[fixture],{windowsHide:true,env:{...process.env,FOLIO_TEST_ROOT:root,FOLIO_DATA_DIR:root,WEBVIEW2_USER_DATA_FOLDER:path.join(root,'profile-'+Date.now()),WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS:`--remote-debugging-port=${debugPort} --remote-debugging-address=127.0.0.1`},stdio:['ignore','pipe','pipe']});
  let stderr='';proc.stderr.on('data',b=>stderr+=b);
  let browser;
  try {
    for(let i=0;i<100;i++){try{browser=await chromium.connectOverCDP(`http://127.0.0.1:${debugPort}`);break;}catch{await new Promise(r=>setTimeout(r,200));}}
    assert.ok(browser,'WebView2 debugging endpoint opened');
    const context=browser.contexts()[0];
    let page=context.pages()[0];
    if(!page)page=await context.waitForEvent('page');
    page.on('pageerror',error=>checks.push({name:'pageerror',error:String(error)}));
    await page.waitForSelector('#document-content h1',{timeout:45000});
    await page.waitForFunction(()=>document.getElementById('document-title').textContent==='fixture.md');
    await page.screenshot({path:path.join(root,'initial.png')});
    console.log(JSON.stringify({title:await page.title(),text:(await page.locator('#document-content').innerText()).slice(0,100),stderr}));
    if(process.env.FOLIO_INSPECT==='1') {
      await fs.writeFile(path.join(root,'session.json'),JSON.stringify({port:debugPort,pid:proc.pid}));
      await new Promise(r=>setTimeout(r,600000));return;
    }
    checks.push({name:'Native Rust/WebView2 opens Markdown from CLI',passed:true});
    const config=async value=>page.evaluate(payload=>window.__TAURI__.core.invoke('request',{action:'test-config',payload}),value);
    const invoke=async(action,payload=null)=>page.evaluate(({action,payload})=>window.__TAURI__.core.invoke('request',{action,payload}),{action,payload});
    const edit=async value=>{await page.locator('button[data-view=split]').click();await page.locator('#source-content').fill(value);await page.waitForTimeout(450);};
    const sample='# Rust edition\n\n**Bold**, *italic*, ~~strike~~ and `inline code`.\n\n[Link](https://example.com)\n\n- First\n  - Nested\n\n> A quote\n\n| Name | Value |\n| --- | --- |\n| Item | café |\n\n![Local image](local.png)\n\n$$E=mc^2$$\n\n```mermaid\nflowchart LR\nA[Read]-->B[Write]\n```\n\n```dot\ndigraph { A -> B }\n```';
    await edit(sample);
    await page.waitForSelector('.diagram svg',{timeout:45000});
    await page.waitForFunction(()=>document.querySelectorAll('.diagram svg').length>=2);
    assert.ok(await page.locator('.katex').count());
    await page.waitForFunction(()=>document.querySelector('#document-content img')?.naturalWidth>0);
    checks.push({name:'Split editor renders math, Mermaid, Graphviz and local image',passed:true});
    await page.locator('#save-document').click();
    await page.waitForFunction(()=>document.getElementById('save-state').textContent==='Saved');
    assert.equal((await fs.readFile(fixture,'utf8')).replace(/\r\n/g,'\n'),sample);
    checks.push({name:'Native atomic save writes latest draft',passed:true});
    await fs.writeFile(fixture,'# External update\n\nFrom disk.');
    await page.waitForFunction(()=>document.querySelector('#document-content h1')?.textContent.includes('External update'));
    checks.push({name:'Clean document reloads after external modification',passed:true});
    await edit(sample+'\n\nUnsaved tail.');
    await fs.writeFile(fixture,'# Conflicting disk copy');
    await page.waitForFunction(()=>document.getElementById('status-message').textContent.includes('Changed on disk'));
    await config({choice:'Cancel'});await page.locator('#save-document').click();await page.waitForTimeout(200);
    assert.equal(await fs.readFile(fixture,'utf8'),'# Conflicting disk copy');
    assert.ok((await page.locator('#source-content').inputValue()).endsWith('Unsaved tail.'));
    await config({choice:'Replace disk version'});await page.locator('#save-document').click();
    await page.waitForFunction(()=>document.getElementById('save-state').textContent==='Saved');
    assert.ok((await fs.readFile(fixture,'utf8')).endsWith('Unsaved tail.'));
    checks.push({name:'Conflict cancel preserves both drafts; explicit replace saves',passed:true});
    await edit(sample+'\n\nUnsaved tail.\n\nExported without saving.');
    assert.ok(!(await fs.readFile(fixture,'utf8')).includes('Exported without saving.'));
    await page.locator('#export-toggle').click();await page.locator('#export-teams').click();
    await page.waitForFunction(()=>document.getElementById('toast').textContent.includes('Copied for Teams'));
    const clip=await invoke('test-clipboard');assert.match(clip.text,/Unsaved tail/);assert.match(clip.html,/<strong>Bold<\/strong>/);assert.match(clip.html,/StartHTML:\d+/);
    assert.match(clip.text,/Exported without saving/);
    checks.push({name:'Real Windows clipboard contains CF_HTML and Unicode text',passed:true});
    await config({export:path.join(root,'export.html')});await page.locator('#export-toggle').click();await page.locator('#export-html').click();
    await page.waitForFunction(()=>document.getElementById('toast').textContent.includes('export.html'),null,{timeout:30000});
    const html=await fs.readFile(path.join(root,'export.html'),'utf8');assert.match(html,/data:image\/png;base64/);assert.match(html,/Unsaved tail/);
    assert.match(html,/Exported without saving/);
    checks.push({name:'Standalone HTML embeds local images and current content',passed:true});
    for(const profile of ['technical','studio','editorial']){
      await config({export:path.join(root,profile+'.pdf')});await page.locator('#export-toggle').click();await page.locator('#export-pdf').click();
      await page.locator(`input[name=pdf-profile][value=${profile}]`).check();await page.locator('#pdf-save').click();
      await page.waitForFunction(name=>document.getElementById('toast').textContent.includes(name),profile+'.pdf',{timeout:90000});
      const bytes=await fs.readFile(path.join(root,profile+'.pdf'));assert.equal(bytes.subarray(0,5).toString(),'%PDF-');assert.ok(bytes.length>20000);
      checks.push({name:`Native ${profile} PDF export`,passed:true});
    }
    await page.locator('button[data-view=read]').click();await page.locator('#theme-toggle').click();
    await page.screenshot({path:path.join(root,'dark.png')});
    await page.locator('#theme-toggle').click();await page.screenshot({path:path.join(root,'light.png')});
    await page.locator('button[data-view=split]').click();await page.screenshot({path:path.join(root,'split.png')});
    await edit('# Keep my draft');await config({choice:'Cancel'});await page.locator('#new-document').click();await page.waitForTimeout(200);
    assert.equal(await page.locator('#source-content').inputValue(),'# Keep my draft');
    await config({choice:'Discard'});await page.locator('#new-document').click();
    await page.waitForFunction(()=>document.getElementById('document-title').textContent==='Untitled.md');
    checks.push({name:'New document honors Cancel and Discard',passed:true});
    await config({save:path.join(root,'new.md')});await edit('# New file\n\nFresh text.');await page.locator('#save-document').click();
    await page.waitForFunction(()=>document.getElementById('save-state').textContent==='Saved');
    assert.equal(await fs.readFile(path.join(root,'new.md'),'utf8'),'# New file\n\nFresh text.');
    checks.push({name:'New document saves through native Save As',passed:true});
    await page.locator('#welcome-button').click();
    await page.waitForFunction(()=>document.getElementById('document-title').textContent==='Welcome to Folio.md' && document.getElementById('status-message').textContent==='Ready to read');
    await page.waitForFunction(()=>document.getElementById('toast').hidden);
    await page.locator('button[data-view=read]').click();
    await page.locator('#reader-scroll').evaluate(el=>el.scrollTop=0);
    await page.screenshot({path:path.join(root,'light.png')});
    await page.locator('#theme-toggle').click();
    await page.waitForFunction(()=>document.getElementById('status-message').textContent==='Ready to read');
    await page.screenshot({path:path.join(root,'dark.png')});
    await page.locator('#theme-toggle').click();
    await page.waitForFunction(()=>document.getElementById('status-message').textContent==='Ready to read');
    await page.locator('button[data-view=split]').click();
    await page.locator('#source-content').evaluate(el=>el.scrollTop=0);
    await page.screenshot({path:path.join(root,'split.png')});
    const session=await context.newCDPSession(page);
    await session.send('Emulation.setDeviceMetricsOverride',{width:760,height:560,deviceScaleFactor:1,mobile:false});
    await page.keyboard.press('Escape');await page.screenshot({path:path.join(root,'compact.png')});
    assert.ok(await page.locator('#export-toggle').isVisible());
    await session.send('Emulation.clearDeviceMetricsOverride');
    await page.locator('#sidebar-toggle').click();
    await page.locator('button[data-view=read]').click();
    await page.locator('#export-toggle').click();
    await page.screenshot({path:path.join(root,'teams-export.png')});
    await page.locator('#export-pdf').click();
    await page.screenshot({path:path.join(root,'pdf-export.png')});
    await page.getByRole('button',{name:'Close PDF options',exact:true}).click();
    checks.push({name:'Light, dark, split and compact layouts captured',passed:true});
    assert.ok(!checks.some(c=>c.error),JSON.stringify(checks.filter(c=>c.error)));
    await fs.writeFile(path.join(root,'report.json'),JSON.stringify({version:'2.0.0',passed:true,checks},null,2));
    console.log(JSON.stringify({passed:true,checks:checks.length}));
  } finally {await browser?.close();proc.kill();await fs.writeFile(path.join(root,'runtime.log'),stderr);}
}
main().catch(async error=>{await fs.writeFile(path.join(root,'report.json'),JSON.stringify({passed:false,checks,error:String(error)},null,2));console.error(error);process.exitCode=1;});
